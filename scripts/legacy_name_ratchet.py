def _change_summary(
    base_ref: str,
    base: Scan,
    head: Scan,
    *,
    max_commits: int | None = None,
) -> _ChangeSummary | None:
    """Classify each first-parent step, falling back to the two endpoints.

    Replaying matters when a line is annotated and a later commit removes it:
    by then it is exempt, so that later edit is exemption churn rather than a
    removal from the ratcheted population. Endpoint arithmetic loses that order.

    Intermediate states are updated by scanning only the paths each commit
    changed. This retains exact chronology without re-grepping the whole tree
    per commit. A range with at most one non-empty transition has no intermediate
    state to recover and reuses the endpoint scans.

    None means a bounded caller exceeded max_commits. It must omit the split
    rather than print the cheaper endpoint classification as exact.
    """
    endpoint = _transition_summary(base, head)
    try:
        base_oid = _git(["git", "rev-parse", f"{base_ref}^{{commit}}"]).strip()
        head_oid = _git(["git", "rev-parse", "HEAD^{commit}"]).strip()
        rev_list_args = ["git", "rev-list", "--first-parent", "--reverse"]
        if max_commits is not None:
            rev_list_args.append(f"--max-count={max_commits + 1}")
        rev_list_args.append(f"{base_oid}..{head_oid}")
        commits = _git(rev_list_args).splitlines()
        if max_commits is not None and len(commits) > max_commits:
            return None
        transitions: list[tuple[str, list[str]]] = []
        previous = base_oid
        for commit in commits:
            parent = _git(["git", "rev-parse", f"{commit}^1"]).strip()
            if parent != previous:
                return endpoint
            transitions.append((commit, _transition_paths(previous, commit)))
            previous = commit
        if previous != head_oid:
            return endpoint

        worktree_paths = _transition_paths("HEAD")
        if sum(bool(paths) for _, paths in transitions) + bool(worktree_paths) <= 1:
            return endpoint

        parts: list[_ChangeSummary] = []
        current = base
        for index, (commit, paths) in enumerate(transitions):
            if index == len(transitions) - 1 and not worktree_paths:
                following = head
            else:
                following = _updated_scan(current, commit, paths)
            parts.append(_transition_summary(current, following))
            current = following
        if worktree_paths:
            parts.append(_transition_summary(current, head))
    except RuntimeError:
        return endpoint

    return _ChangeSummary(
        added=sum(part.added for part in parts),
        annotated=sum(part.annotated for part in parts),
        removed=sum(part.removed for part in parts),
        moved=sum(part.moved for part in parts),
        net=sum(part.net for part in parts),
    )


def _move_label(n: int) -> str:
    return "excused move" if n == 1 else "excused moves"


def _mint_budget(head_total: Counter[str], base_total: Counter[str]) -> Counter[str]:
    """How many of each text the repo actually gained — the whole charge available.

    Computed once for the run and spent down by :func:`_minted`, because the
    charge is a repo-wide quantity and the files that can claim it are counted
    one at a time. Recomputing it per file hands every destination the same
    budget: delete one copy of a line from A, add one to each of B and C, and
    both B and C independently look like the only mint of a text the repo gained
    once — two failures reported for one addition, and one of them a move.
    """
    return +Counter(
        {text: n - base_total.get(text, 0) for text, n in head_total.items()}
    )


def _minted(
    path: str,
    head_by_file: dict[str, Counter[str]],
    base_by_file: dict[str, Counter[str]],
    budget: Counter[str],
) -> tuple[Counter[str], Counter[str]]:
    """``(minted, moved)`` for ``path``: text the repo did not have, and text it did.

    Spends ``budget`` — see :func:`_mint_budget`. Callers must iterate paths in a
    stable order: when a text lands in several files and the repo gained fewer
    copies than that, which destination is charged is arbitrary but the count is
    not, and an arbitrary-but-unstable answer would flake.

    Per-file counting is right and the module docstring's defence of it stands: a
    repo total hides a real addition behind an unrelated deletion elsewhere. But
    it only keeps a move at net zero *within* one file. Move a branded line from
    A to B and B goes ``0 -> 1`` while A drops, so the gate fails a change that
    minted nothing (#882).

    That mattered more than the spurious red, because the remedy the failure text
    offered was an exemption, and none of the three reasons rule 3 recognises —
    compat alias, redirect, pinned wire format — describes a move. The only way
    past the gate was to write a reason that was not true, into the one
    annotation whose whole value is that its reasons are true.

    So a move is recognised here rather than annotated away. A line is a move
    when the repo-wide count of that exact text did not go up: the name existed,
    in those words, and now sits somewhere else. It is minted when the count did
    go up, which no rearrangement can produce. Both shapes are covered, including
    a line moving between two files that both already exist — the likelier shape
    during a consolidation wave, and the one ``--find-renames`` cannot see.

    Strictness is unchanged for genuinely new text: a new name has no matching
    deletion to pair with, so its repo-wide count rises and it fails.

    **What text-matching cannot decide, and why it is reported instead.** The
    pairing is by text, not by provenance — nothing here knows that the deletion
    it paired with is the *same* line. A change that adds a genuinely new
    occurrence in one file while coincidentally deleting a byte-identical line
    somewhere unrelated comes out flat, and the new one is excused.

    No count fixes that, for the same reason the exempt-and-add swap below is not
    fixable: the two cases are identical in every number, and differ only in
    intent. ``--find-renames`` does not settle it either — it answers a narrower
    question and misses the common shape entirely.

    So it takes the same answer as the swap: every excused move is printed, on
    the passing path, with the base file whose deletion paid for it. A laundered
    mint stays visible in the CI log even though the gate passes, which is the
    most a text comparison can honestly offer.
    """
    new_here = head_by_file.get(path, Counter()) - base_by_file.get(path, Counter())

    minted: Counter[str] = Counter()
    moved: Counter[str] = Counter()
    for text, added_here in sorted(new_here.items()):
        # A file can gain two copies of a line the repo only gained one of: one
        # moved in, one is new. Split the tally rather than picking a side, and
        # take the charge out of the shared budget so the next file cannot be
        # charged for the same addition.
        charge = min(added_here, budget[text])
        budget[text] -= charge
        minted[text] = charge
        moved[text] = added_here - charge
    return +minted, +moved  # unary plus drops the zero entries


def _report_excused_moves(
    excused: dict[str, Counter[str]],
    base_by_file: dict[str, Counter[str]],
    head_by_file: dict[str, Counter[str]],
) -> None:
    """Name every line the move check let through, and what paid for it.

    The counterpart to :func:`_report_new_exemptions`, for the same reason and
    with the same honesty. Pairing an addition with a deletion by text cannot
    know the two are the same line, so a change that adds a genuinely new
    occurrence while coincidentally deleting a byte-identical one elsewhere comes
    out flat and is excused. No count separates that from a real move — they are
    identical in every number — so it is reported rather than adjudicated.

    Printed on the passing path, because passing is the only path this takes.
    Naming the base file whose deletion paid for each one is what makes it
    checkable: a reviewer who sees an unrelated file named there has found a
    laundered mint, and nothing else in CI would have shown it.

    A source is a file whose count of that text actually WENT DOWN, not merely
    one that had it. Every file holding an unchanged copy also contains the text,
    so listing on containment names bystanders as sources — and since the list is
    truncated, an alphabetically earlier bystander can push the real source out of
    view entirely. That turns the one output a reviewer is meant to check into
    noise, which is worse than not printing it.
    """
    if not excused:
        return

    total = sum(sum(c.values()) for c in excused.values())
    print(f"{total} line(s) treated as moved rather than added — the same text left")
    print(
        "another file in this change. Check the pairing is real and not a coincidence:"
    )
    for path in sorted(excused):
        for text, n in sorted(excused[path].items()):
            came_from = sorted(
                p
                for p, c in base_by_file.items()
                if p != path and c[text] > head_by_file.get(p, Counter())[text]
            )
            print(f"  {path}: {'x' + str(n) + ' ' if n > 1 else ''}{text[:80]}")
            print(f"      was in: {_truncated(came_from)}")
    print()


def _truncated(paths: list[str]) -> str:
    """Render a path list for a report line, capped so one line stays one line.

    Shared by both reports that name files, so the cap and the empty-list wording
    cannot drift apart between them. The cap is what forces those reports to list
    only files that genuinely changed rather than every file containing the text:
    once the list is truncated, a bystander can displace the real source.
    """
    shown = ", ".join(paths[:3]) or "an unknown file"
    return shown + (f" (+{len(paths) - 3} more)" if len(paths) > 3 else "")


def _report_removed_exemptions(
    base_by_file: dict[str, Counter[str]], head_by_file: dict[str, Counter[str]]
) -> None:
    """Name every exempt line this change removed. Reports; never fails.

    The other half of :func:`_report_new_exemptions`, and the gap that let a
    demonstrated data-loss change pass both required gates green.

    Either marker means "the ratchet may ignore this line". Neither has ever
    meant "this line is protected", and nothing enforced that reading — but a
    marker looks like protection, so lines carrying one were treated as
    handled. Deleting one *lowers* a file's non-exempt count, which the ratchet
    reports as progress. A sweep over two plugin files removed a dual-read alias
    that decides which ``.env`` keys survive a redeploy; ratchet and sentinel
    both exited 0. Three of the aliases involved already carried this marker.

    Why this reports rather than fails, which was measured rather than assumed:
    across the last 400 commits, seven removed a marked line and **none** was a
    genuine removal of protection. Every one reworded or consolidated markers
    while keeping the alias — one collapsed six into one. A failing rule keyed on
    text identity would have produced seven false positives and no true ones, and
    a rule keyed on per-file counts would have failed the consolidation too.
    Nothing textual separates "consolidated the alias" from "deleted the alias";
    that judgement is irreducibly human, so this hands a human the fact rather
    than guessing.

    **What to do when this fires.** Confirm the protection still exists in some
    form. If the line was reworded or merged, nothing is wrong. If it is simply
    gone, the dependant it existed for is now broken and nothing else in CI will
    say so. Anything whose removal breaks an already-installed user belongs in
    ``do_not_touch_sentinel.py``, which pins exact text and does fail — this
    marker is not a substitute for that and never was.

    Each line is printed with the base-tree file it left, because "confirm what
    it stood for still exists" is not answerable from the text alone — the reader
    needs somewhere to look, and short markers plausibly live in more than one
    file. Sources are the files whose count for that text actually dropped, not
    every file that happens to contain it: listing on containment would name
    untouched bystanders, and since the list is truncated a bystander can push
    the real source out of view. Same rule, and same reason, as
    :func:`_report_excused_moves`.

    **Counted per file, not as a repo-wide net**, which is the difference
    between reporting this incident and missing it. A repo-wide ``before -
    after`` cancels a deletion against any byte-identical exempt line added
    anywhere else in the same change, and the motivating incident was a *sweep*
    — the shape most likely to delete an alias in one file while writing
    something identical in another. Netting three losses against two unrelated
    gains prints "1", names the file that lost three, and reads as the mildest
    possible version of the worst case. Losses are therefore summed gross,
    across only the files whose own count fell.

    Gross counting surfaces one case netting hid: text that left one file and
    appeared in another, which is usually a move and usually benign. That is
    reported rather than suppressed — a move is exactly the "reworded or
    consolidated" case a human is being asked to confirm — but the destination
    is named on the same line, so the benign reading is available without
    grepping for it. Suppressing it instead would restore the blind spot.
    """
    # text -> {path: how many left THAT path}. Gains elsewhere never subtract.
    drops: dict[str, Counter[str]] = {}
    for path, counts in base_by_file.items():
        head_counts = head_by_file.get(path, Counter())
        for text, n_base in counts.items():
            lost = n_base - head_counts[text]
            if lost > 0:
                drops.setdefault(text, Counter())[path] = lost
    if not drops:
        return

    n = sum(sum(c.values()) for c in drops.values())
    # Not split by kind, unlike the new-exemption report. The populations are the
    # other way round here — seven removals across four hundred commits, against
    # eleven new exemptions in a single PR — so the wall this list can become is
    # hypothetical, and a split would buy nothing a reader cannot see from the
    # marker still sitting in each printed line. The guidance covers both kinds
    # instead, since a floor mention has no alias to survive and telling a reader
    # to look for one would be exactly the false reason this marker split exists
    # to stop. Worth revisiting if the removal rate ever approaches the other's.
    print(
        f"\n{n} exempt line(s) removed by this change. A marker marks a line the\n"
        "ratchet ignores, NOT a line that is protected — deleting one lowers the\n"
        "count and reads as progress. Confirm what each one stood for still exists\n"
        "in some form — the alias it declared, or the text that could not be\n"
        "correct without the name:"
    )
    for text, per_file in sorted(drops.items()):
        count = sum(per_file.values())
        suffix = f"  (x{count})" if count > 1 else ""
        print(f"  {text.strip()[:100]}{suffix}")
        print(f"      was in: {_truncated(sorted(per_file))}")
        gained = sorted(
            p
            for p, c in head_by_file.items()
            if c[text] > base_by_file.get(p, Counter())[text]
        )
        if gained:
            where = _truncated(gained)
            print(f"      identical text added in: {where} — likely a move")


def _report_new_exemptions(
    before: Counter[str], after: Counter[str], base: str
) -> None:
    """Name every exempt line this change wrote, whether or not it fails.

    The one thing a count-based ratchet cannot decide for itself, and the reason
    this report exists. Marking an existing line exempt lowers a file's
    non-exempt count by one, which is exactly enough headroom to add a new
    unmarked occurrence in the same file and come out flat.

    No count separates that from the legitimate case. Both look identical per
    file — non-exempt flat, exempt up one, total up one — because the difference
    is *which* line carries the marker, not how many do.

    The **texts** are not identical, though, and since :func:`_minted` compares
    those the swap now fails rather than passing quietly: a legitimate alias adds
    exempt text and nothing chargeable, while the swap adds non-exempt text the
    repo never had. This report is no longer the only thing standing between that
    move and a green tick.

    It is still printed, on the passing path as well. An exemption is the move
    that buys headroom, and a deliberate one — an alias landing in the same PR as
    unrelated work — should never be made quietly even when it is legitimate.

    Which is why the list is filtered to the lines this change actually wrote,
    rather than every exempt line the file happens to hold. Re-greping and
    printing all of them puts a file's whole accumulated pile under a header
    counting one, sends the reader to lines that are not in the diff, and reads
    as self-contradictory — which invites distrusting the total rather than the
    list. Phase 5's dual-read wave is exactly the change that builds those piles,
    so every later PR touching those files would reprint them. A reader who
    learns the list is mostly noise stops reading it, and that is the failure
    this report exists to prevent.

    **Git decides both halves.** It selects the lines, and it also selects the
    files. Selecting files by a risen exempt tally leaves a hole: remove one
    exemption and add another in the same file and the tally is flat, so the file
    is never examined and the new exemption is never printed. The gate still
    catches the dangerous form of that — un-marking a line raises the non-exempt
    count and :func:`_minted` charges the text — but a brand-new reason nobody is
    pointed at is precisely what this report exists to prevent, and during a
    dual-read wave a one-for-one swap inside a file already full of exemptions is
    unremarkable in a diff.

    The tally is kept only as the fallback for when git cannot answer, since a
    selection that is too narrow beats one that is arbitrary.

    **Split by kind, because one list of eleven is not a signal.** This is the
    only place the difference between the two markers is read. Floor mentions
    outnumber aliases because they accrue from editing documentation rather than
    from renaming anything — caura-daemon#136 landed eleven in one PR, four of
    them aliases — so undifferentiated they are a wall a reviewer scrolls past,
    which is the same failure the reason-grouping below prevents, one level up.

    This is a better signal, not a quieter one: nothing is dropped, the totals
    are unchanged, and both kinds are still printed in full with their reasons.
    """
    # Files git says this change touched, narrowed to those that hold an exempt
    # line at all. The union with the risen-tally set is belt and braces: when
    # ``changed`` is available it already contains every risen file, and when it
    # is ``None`` the tally is all there is.
    changed = _changed_paths(base)
    risen = {p for p, n in after.items() if n > before.get(p, 0)}
    paths = risen if changed is None else {p for p in after if p in changed} | risen
    if not paths:
        return

    # Grouped by kind, then by reason. Reason-grouping is there because the wall
    # is the failure mode: a dual-read wave exempts dozens of lines carrying one
    # identical reason, and at that length the list stops being read — which
    # costs exactly the thing it is for, since the swap this report exists to
    # expose shows up as the ONE reason that does not match its neighbours.
    # Collapsing the repeats is what makes the odd one visible instead of burying
    # it on line forty. Kind-grouping is the same argument one level up: a floor
    # mention's reason never matches an alias's, so mixing them puts a permanent
    # wall between the aliases and the reader.
    by_kind: dict[str, dict[str, list[tuple[str, str, str]]]] = {}
    shown_total = 0
    listed_paths: set[str] = set()
    unfiltered: list[str] = []
    for path in sorted(paths):
        here = [
            (lineno, text.strip(), kind)
            for _, lineno, text, kind in _grep(None, pathspec=_literal(path))
            if kind is not None
        ]
        if not here:
            continue
        # git decides which of the file's lines this change is responsible for.
        # An existing line that gains a marker is a rewrite, so git calls it
        # added and it stays in — which matters, because that is the headroom
        # move this report exists to expose.
        touched = _added_lines(base, path)
        if touched is None:
            # Diff unreadable. Falling back to every exempt line in the file
            # rather than to silence, on the same trade the offender report
            # makes below: too many lines is a nuisance and none is a dead end.
            # Named out loud, though, because unlike below this report puts a
            # number on its own list.
            picked = here
            unfiltered.append(path)
        else:
            picked = [(n, t, k) for n, t, k in here if int(n) in touched]
        # Empty is now a real answer rather than a failure — a file this change
        # only deleted from, or touched somewhere other than its exempt lines,
        # adds nothing and every marker it holds predates the change. Printing
        # them would be #894 reintroduced through the file-selection door, which
        # is the specific risk of selecting on the diff rather than the tally.
        if not picked:
            continue
        shown_total += len(picked)
        listed_paths.add(path)
        for lineno, stripped, kind in picked:
            tail = _reason(stripped, kind)
            by_kind.setdefault(kind, {}).setdefault(
                tail.strip() or "(no reason given)", []
            ).append((path, lineno, stripped))

    # Nothing survived the per-line filter: every candidate file holds only
    # exemptions that predate this change. Silence is right — the previous
    # version could not reach here, because a risen tally guaranteed something
    # to print.
    if not by_kind:
        return

    # Both counted while picking rather than derived from ``by_kind`` afterwards,
    # so neither tracks the shape of that dict — and so the header stays a count
    # of what was PICKED rather than of what was successfully classified. The two
    # are the same number today and structurally cannot differ, since
    # :func:`_kind` only ever returns a :data:`_KINDS` key. If they ever did, a
    # header larger than the sections beneath it is the visible symptom, which is
    # worth more than an agreement enforced by construction.
    print(
        f"{shown_total} exempt line(s) written by this change in "
        f"{len(listed_paths)} file(s) —"
    )

    # In ``_KINDS`` order rather than by size, so aliases lead even when the
    # mentions outnumber them — which is the usual case and the reason for the
    # split.
    present = [
        (marker, sum(len(lines) for lines in by_kind[marker].values()))
        for marker in _KINDS
        if marker in by_kind
    ]
    if len(present) > 1:
        # The line the split exists for. Skipped when only one kind is present,
        # where it would only restate the section header underneath it.
        print(", ".join(f"{n} {_KINDS[marker].label}" for marker, n in present) + ".")
    if unfiltered:
        named = ", ".join(unfiltered[:4]) + (
            f" (+{len(unfiltered) - 4} more)" if len(unfiltered) > 4 else ""
        )
        print(
            f"  (diff unreadable for {len(unfiltered)} file(s): {named} — every "
            "exempt line they hold is listed, so some may predate this change)"
        )

    for marker, n in present:
        # ``spec``, not ``kind``: ``kind`` is the marker literal a few lines up,
        # and one name for two types inside one function costs the reader a
        # lookup at every use.
        spec = _KINDS[marker]
        print(f"\n{n} {spec.label} — {spec.guidance[0]}")
        for line in spec.guidance[1:]:
            print(line)
        by_reason = by_kind[marker]
        for reason, lines in sorted(
            by_reason.items(), key=lambda kv: (-len(kv[1]), kv[0])
        ):
            if len(lines) <= _EXEMPTION_GROUP_AT:
                for path, lineno, stripped in lines:
                    print(f"  {path}:{lineno}: {stripped[:100]}")
                continue
            files = sorted({path for path, _, _ in lines})
            shown = ", ".join(files[:4]) + (
                f" (+{len(files) - 4} more)" if len(files) > 4 else ""
            )
            print(f"  {len(lines)}x  {reason[:80]}")
            print(f"      in {len(files)} file(s): {shown}")
    print()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Ratchet on lines carrying the legacy brand."
    )
    parser.add_argument(
        "--base", default="origin/main", help="tree-ish to compare against"
    )
    parser.add_argument(
        "--report", action="store_true", help="print counts and change split; exit 0"
    )
    args = parser.parse_args()

    # Scan the working tree first so report mode can retain its "counts never
    # fail" contract even when its optional comparison base is unreadable.
    try:
        head_scan = scan(None)
    except RuntimeError as exc:
        print(exc, file=sys.stderr)
        return 2

    head = head_scan.counts()
    if args.report:
        print(f"{sum(head.values())} lines across {len(head)} files")
        for path, n in sorted(head.items(), key=lambda kv: (-kv[1], kv[0])):
            print(f"  {n:>4}  {path}")

    # A bad base must still be exit 2 for the gate. In report mode it only makes
    # the change split unavailable; the current-tree inventory above is valid.
    try:
        base_scan = scan(args.base)
    except RuntimeError as exc:
        if args.report:
            print(f"Change from {args.base} unavailable: {exc}", file=sys.stderr)
            return 0
        print(exc, file=sys.stderr)
        return 2

    base = base_scan.counts()

    if args.report:
        report_summary = _change_summary(args.base, base_scan, head_scan)
        print(
            f"Change from {args.base}: {report_summary.added} added, "
            f"{report_summary.annotated} annotated, "
            f"{report_summary.removed} removed, "
            f"{report_summary.moved} {_move_label(report_summary.moved)} "
            f"({report_summary.net:+d} net)."
        )
        return 0

    if not head and not base:
        # A pathspec that matches nothing exits 1 with an empty stderr, exactly
        # like a clean tree — so a broken scan reads as "nothing to report" and
        # the gate passes every PR from then on, silently, for the rest of the
        # programme. Both trees empty is either that or a finished migration,
        # and both want a human.
        print(
            f"Found no '{LEGACY_NAME}' lines in either tree.\n"
            "Either the pattern or the pathspec is broken — in which case this gate has\n"
            "been passing without checking anything — or the migration is complete and\n"
            "this gate should be deleted along with the last of the old names."
        )
        return 1

    head_by_file, base_by_file = head_scan.by_file, base_scan.by_file
    budget = _mint_budget(head_scan.total, base_scan.total)

    grown = {}
    excused: dict[str, Counter[str]] = {}
    generated_changelogs: list[str] = []
    release_branch = _release_please_branch()
    # Sorted: the budget is spent as files are visited, so the order decides which
    # destination is charged when one text lands in several. Arbitrary is fine;
    # unstable is not.
    for path in sorted(head):
        if release_branch and path.rsplit("/", 1)[-1].upper().startswith("CHANGELOG"):
            if head[path] > base.get(path, 0):
                generated_changelogs.append(path)
            continue
        before, n = base.get(path, 0), head[path]
        # Deliberately NOT gated on ``n > before``. A file that drops one branded
        # line and adds a different, brand-new one in the same edit comes out
        # flat, and a count-first filter skips it before anything looks at the
        # text — so the new name is never surfaced and the gate reports "No new
        # lines." Comparing the text is what catches it; the count was only ever
        # a cheap proxy for "worth looking at", and it is the wrong one.
        minted, moved = _minted(path, head_by_file, base_by_file, budget)
        if moved:
            excused[path] = moved
        if minted:
            grown[path] = (before, n, minted)

    _report_new_exemptions(base_scan.exempt(), head_scan.exempt(), args.base)
    _report_removed_exemptions(base_scan.exempt_by_file, head_scan.exempt_by_file)
    _report_excused_moves(excused, base_by_file, head_by_file)

    if generated_changelogs:
        print(
            f"{len(generated_changelogs)} generated CHANGELOG file(s) exempt on this "
            "release-please branch (titles quoted from history):"
        )
        for path in sorted(generated_changelogs):
            print(f"  {path}")

    if not grown:
        gate_summary = _change_summary(
            args.base,
            base_scan,
            head_scan,
            max_commits=_GATE_REPLAY_LIMIT,
        )
        if gate_summary is None:
            print(
                "No new lines fail the gate. Change split omitted: the range exceeds the "
                f"{_GATE_REPLAY_LIMIT}-commit gate replay limit; run --report "
                "for the exact split."
            )
            return 0
        if gate_summary.added:
            print(
                f"No new lines fail the gate. {gate_summary.added} added, "
                f"{gate_summary.annotated} annotated, "
                f"{gate_summary.removed} removed, "
                f"{gate_summary.moved} {_move_label(gate_summary.moved)} "
                f"({gate_summary.net:+d} net)."
            )
        elif gate_summary.annotated or gate_summary.removed or gate_summary.moved:
            print(
                f"No new lines. {gate_summary.annotated} annotated, "
                f"{gate_summary.removed} removed, {gate_summary.moved} "
                f"{_move_label(gate_summary.moved)} "
                f"({gate_summary.net:+d} net)."
            )
        else:
            print("No new lines.")
        return 0

    print(f"This change adds the legacy name in {len(grown)} file(s).\n")
    for path, (before, after, minted) in sorted(grown.items()):
        # A flat or falling count can still fail: what failed is the text, not the
        # tally, and saying so stops the reader arguing with the arithmetic. Flat
        # and falling are said separately because they are different sentences —
        # calling a count that dropped "unchanged" invites exactly the argument
        # the note exists to head off.
        if after > before:
            note = ""
        elif after == before:
            note = ", count unchanged — the text is new"
        else:
            note = ", count fell — the text is new"
        print(f"  {path}  ({before} -> {after}{note})")
        # Lines carrying minted text AND actually added by this change. Both
        # halves are needed. Without the text filter the report names every
        # branded line in the file; without the diff it names the first line
        # holding the text, which in a file that already had one is a line
        # nobody touched.
        added = _added_lines(args.base, path)
        candidates = [
            (lineno, text.strip())
            for _, lineno, text, kind in _grep(None, pathspec=_literal(path))
            if kind is None and text.strip() in minted
        ]
        shown = (
            candidates
            if added is None
            else [(n, t) for n, t in candidates if int(n) in added]
        )
        # Falling back to every occurrence rather than to silence: if the diff
        # could not be read, too many lines is a nuisance and none is a dead end.
        #
        # The ``or candidates`` also covers an empty-but-successful diff. Unlike
        # the exemption report, silence is NOT right here: this branch only runs
        # for a file that minted text the repo never had, so something was added
        # and an empty intersection means the two disagree. Naming every
        # occurrence keeps a real offender on screen.
        shown = shown or candidates
        for lineno, stripped in shown:
            print(f"      {lineno}: {stripped[:110]}")

        # When a change adds several identical lines and only some are minted,
        # every one of them is a line this change added and they cannot be told
        # apart — that is what identical means. Naming one would be a guess
        # dressed as a finding, so all are printed and the split is stated.
        for text, new in sorted(minted.items()):
            here = sum(1 for _, t in shown if t == text)
            if here > new:
                print(
                    f"      ^ {here} added lines share this text; {new} new, "
                    f"{here - new} moved in from elsewhere — identical, so which is which"
                    " cannot be told apart"
                )
    print(
        f"\nRule 7 of the sunset plan: mint nothing new named '{LEGACY_NAME}'. Every one adds a\n"
        "redirect to keep forever and spends a rename option. Use the Caura name instead.\n\n"
        "A line moved here from another file is not this: text the base tree already\n"
        "had somewhere is recognised as a move and does not fail. Every line above is\n"
        "text this repo did not have before, so no rearrangement produced it.\n\n"
        "If the addition is deliberate — a compat alias, a redirect, a test pinning the old\n"
        f"wire format, all of which rule 3 requires — append '{EXEMPT_MARKER}: <reason>' to the\n"
        "line. It is then exempt, and the reason is visible in the diff.\n\n"
        "If instead the line only NAMES something the rename will never reach, and cannot\n"
        "be correct without the literal — a pasteable command, an on-disk path, a served\n"
        f"mirror path — append '{FLOOR_MARKER}: <reason>' instead. Identical exemption,\n"
        "different claim: nothing is declared there, so it is counted apart and the\n"
        "aliases stay readable. Check the claim before you make it — if rewording the\n"
        "line would leave it correct, reword it rather than marking it."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
