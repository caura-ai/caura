#!/usr/bin/env python3
"""Fail a PR that mints a new legacy-named thing.

Hard rule 7 of the sunset plan: never mint anything new carrying the old brand. A
service, secret, topic, env var, file or identifier named that way adds a
redirect somebody has to keep forever and spends a rename option that was already
paid for. The programme runs for weeks with ordinary feature work alongside it,
so the rule needs a gate rather than a reviewer's attention.

What it does: compares the legacy-name lines per file, by TEXT, between the tree
being built and the base tree, and fails a file that carries text the repo did
not have before. Not a count comparison — a flat or falling count can still hide
newly minted text, and a risen one can be nothing but a move. See "Why the count
is not the check" below. Decreases are the point of the programme and are
reported as progress.

Why per file rather than a repo total: a total hides an addition behind an
unrelated deletion elsewhere in the same PR, while a per-file count keeps a
within-file move (delete plus re-add) at net zero, which is most of what the
infrastructure and rewrite waves do.

A move BETWEEN files is kept at net zero too, and needs a second check to be —
the per-file count alone fails it, because the destination goes up. So a line
whose exact text the base tree already had somewhere is treated as moved rather
than minted. See :func:`_minted`.

Why against the base tree rather than a committed baseline: a baseline file goes
stale, churns on every move, and has to be regenerated by the same person the
gate is pointed at. On a ``pull_request`` the checkout is already the merge
commit, so the comparison against ``main`` is exactly this PR's contribution and
there is nothing to maintain.

**The escape hatch, and the two claims it can make.** A line carrying either
marker is not counted. The gate cannot tell them apart — the pass/fail decision
never reads which one is there, and nothing that failed before passes now. They
differ only in what a reviewer has to check, which is the only thing a marker
was ever for. Put one on the line with a reason and it lands in the diff.

``legacy-name-ok`` is rule 3's hatch: something new that BEARS the old name — a
compat alias, a redirect, a test pinning the old wire format.

``legacy-name-floor`` is a line that merely NAMES something the rename will never
reach, and cannot be correct without the literal: a pasteable command, an on-disk
path, a served mirror path. Nothing is declared and the footprint does not grow.

Why a second marker rather than a convention inside the reason text. Audited at
full coverage across the seven repos: 622 markers — **340 aliases, 274 floor
mentions**, and 8 on lines that should have been reworded rather than marked at
all. Forty-four per cent of every exemption in the programme is the kind rule 3
has nothing to say about, and the only thing separating them is prose.

The two populations also grow from different work. An alias arrives when
something is renamed. A floor mention arrives whenever a document that mentions
the product's own name is EDITED — re-flowing a comment mints new text even as
the file's count falls, and a marker cannot come off a line without the literal
coming off with it. So that half of the pile is fed by maintaining documentation
rather than by sweeping the brand, and it grows for as long as the docs are
maintained. caura-daemon#136 is the shape of it in one PR: eleven exemptions,
four of them aliases, and a reviewer facing eleven undifferentiated entries
stops reading.

What this is NOT is a fix for false reasons at scale. Only 11 of the 622 (1.8%)
put alias language on a non-alias line, and 218 of the 274 floor mentions
already say "floor", "pinned" or "frozen" in their own reason text. Authors have
been drawing the distinction correctly all along; the gate has had nowhere to
record it, so it could not count on it. This makes the distinction structural.

Both are a claim someone has to stand behind, and a floor marker is falsifiable
in one move: reword the line without the old name, and if it is still correct
then the marker was false and the line should carry no marker at all.

**Why the count is not the check.** A file's total is a cheap proxy for "worth
looking at", and it is the wrong one in both directions. It fails a cross-file
move, where the destination rises and nothing was minted. And it passes a
same-file swap, where one branded line is dropped and a different, brand-new one
added in the same edit: flat total, so a count-first filter never looks at the
text and the gate reports "No new lines." Both are decided by comparing the text
instead, which is what :func:`_minted` does for every file rather than only the
ones whose tally rose.

That also closes the exempt-and-add swap, which counting genuinely cannot: mark
an existing line exempt and fill the freed slot with a new unmarked one and every
tally matches a legitimate marked alias — non-exempt flat, exempt +1, total +1 —
because the difference is *which* line carries the marker. The texts differ
though. A legitimate alias adds new EXEMPT text and no new non-exempt text, so
there is nothing to charge; the swap adds non-exempt text the repo never had.
Every newly exempted line is still printed, on the passing path too, because the
report is what made the hole visible and stays useful when the swap is deliberate.

**What this still does not enforce.** The move check pairs an addition with a
deletion by text, so it cannot know the two are the same line: adding a genuinely
new occurrence while coincidentally deleting a byte-identical one elsewhere comes
out flat and is excused. That one is identical in every number AND in every text,
so nothing here can decide it — every excused move is printed with the file whose
deletion paid for it, and a reviewer who sees an unrelated file there has found
the laundering.

Usage::

    scripts/legacy_name_ratchet.py                     # compare against origin/main
    scripts/legacy_name_ratchet.py --base <tree-ish>
    scripts/legacy_name_ratchet.py --report            # counts + change split; never fails
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from collections import Counter
from typing import NamedTuple, overload

# The legacy brand. Matched case-insensitively, so every casing in the tree
# counts — prose, identifiers and SCREAMING_SNAKE env names alike. This is the
# only place the literal appears in this file, and it carries the marker so the
# gate does not trip over its own pattern; excluding the file instead would leave
# a hole in the scan.
LEGACY_NAME = "memclaw"  # legacy-name-ok: the pattern this gate searches for

# Kept deliberately ugly so they are never typed by accident and always read as a
# decision rather than a formatting artifact.
EXEMPT_MARKER = "legacy-name-ok"
FLOOR_MARKER = "legacy-name-floor"


class _Kind(NamedTuple):
    """What the report calls one marker, and the guidance printed under it.

    A NamedTuple rather than a bare pair because ``_KINDS[marker][0]`` says
    nothing about which half it is, and the file already uses one for
    :class:`Scan`.
    """

    label: str
    guidance: tuple[str, ...]


# The markers, in the order the report lists them, with what it calls each.
# Aliases lead whether there are four of them or one: they are what rule 3 wants
# eyes on, so their position must not depend on a tally. The label carries its
# own ``(s)`` the way every other count in this file does.
#
# The gate never reads this. Both markers exempt a line identically — see
# :func:`_kind` — and the split exists purely so the report can say "4 compat
# aliases and 6 floor mentions" where it used to say "11 exemptions".
#
# **Keys must be lowercase**, or the entry is never found and its lines vanish
# from the report while still exempting. :func:`_kind` explains why.
#
# **Adding a kind is not only a line here.** The failure text at the end of
# :func:`main` is the only place the gate tells an author a marker exists at all,
# and it is written out per kind rather than driven from this table, because it
# is imperative advice addressed to someone whose build just went red and does
# not fit the same mould as the report's. A new kind wants a paragraph there too;
# omitted, it is a marker nobody discovers.
#
# Guidance is a tuple of already-wrapped lines rather than one string with
# newlines in it, for the same reason this file prints its other prose a line at
# a time: re-flowing an embedded ``\n`` is how a paragraph silently loses its
# shape, and the first line has to be joinable to a count.
_KINDS: dict[str, _Kind] = {
    EXEMPT_MARKER: _Kind(
        "compat alias(es)",
        (
            "rule 3's escape hatch, and what this report is for.",
            "Check each is a compat alias, a redirect or a pinned wire format,",
            "and not headroom for a new name:",
        ),
    ),
    FLOOR_MARKER: _Kind(
        "floor mention(s)",
        (
            "a permanent name in text, not a new declaration.",
            "Check the line cannot be correct without the literal: a pasteable",
            "command, an on-disk path, a served mirror path. If rewording it",
            "would leave it correct, the claim is false and it should carry no",
            "marker at all:",
        ),
    ),
}

# Matched as a bounded token, not a bare substring. A substring test exempts any
# line that merely contains a marker inside a longer word — "not
# legacy-name-okay to leave in" would silence a real occurrence, which is a hole
# in the gate rather than a nuisance. Case-insensitive for the same reason the
# name match is: a marker typed ``Legacy-Name-OK`` is plainly a decision, and
# failing it would be a spurious red on a line someone deliberately annotated.
#
# Bounded on BOTH sides, and the two are not the same check: the lookahead stops
# ``legacy-name-okay`` and the lookbehind stops ``somelegacy-name-ok``. Either one
# alone leaves the hole open from the other end.
#
# Neither boundary is a comment prefix — comment syntax differs across the file
# types this scans, and JSON has none at all while still being somewhere an alias
# can legitimately live.
#
# One pattern for both markers rather than one each, so those boundaries are
# stated once and cannot drift apart: the lookbehind and lookahead sit outside
# the alternation, so every marker gets both. Alternation order is not load
# bearing here because neither marker is a prefix of the other — if a third is
# ever added that IS a prefix of another, list the longer one first, since Python
# takes the first alternative that matches rather than the longest.
EXEMPT_RE = re.compile(
    rf"(?<![\w-])(?P<marker>{'|'.join(re.escape(m) for m in _KINDS)})(?=[\s:]|$)",
    re.IGNORECASE,
)


def _kind(text: str) -> str | None:
    """Which marker exempts this line, or ``None`` if none does.

    Returns the marker literal rather than its label, so the marker stays the one
    identity a kind is keyed by and :data:`_KINDS` stays the only place a label
    is written down.

    The gate's decision reads only whether this is ``None``. That is what keeps
    the two markers interchangeable at the point of failure: a line that passed
    before passes now, and a marker a reviewer thinks is the wrong KIND is still
    a marker, so mislabelling one can never turn a red build green or a green one
    red. Only the report reads which.

    **When both claims are true of one line, the alias wins.** This is not the
    degenerate case it looks like: 28 lines across the fleet name a permanent
    thing AND declare a dual-read in the same breath, e.g. an image tag whose
    repository name is frozen while its version is read from both spellings.
    Both claims are true, one line can only carry one marker, and picking by
    position on the line would make the answer depend on which end the author
    typed first.

    So precedence is :data:`_KINDS` order, which puts the alias first: an alias
    reported as a floor mention is a rule 3 decision nobody looked at, while a
    floor mention reported as an alias is one extra line in the list that most
    wants reading anyway. Under-counting the aliases is the expensive direction,
    so the tie breaks away from it.

    The lowercasing is what keeps the result a usable :data:`_KINDS` key, and it
    is load bearing rather than tidiness. A kind that does not match a key is
    still not ``None``, so the line stays exempt and the gate stays green — while
    the report, which looks the kind up to decide which list it belongs in, finds
    nothing and drops the line without a word. Exempt but unprinted is the one
    outcome this report exists to prevent.
    """
    found = {m.group("marker").lower() for m in EXEMPT_RE.finditer(text)}
    return next((marker for marker in _KINDS if marker in found), None)


def _reason(text: str, kind: str) -> str:
    """What ``kind``'s marker says on this line: the text between it and the next.

    Lives beside :func:`_kind` rather than inline in the report because the two
    have to agree about which marker owns the line, and a rule split across two
    call sites is one that eventually disagrees with itself.

    Bounded on BOTH ends, and the second bound is the one that is easy to miss.
    Slicing to end-of-line is right for the ordinary single-marker case and wrong
    the moment a line carries two: with the winning marker written first, the
    tail swallows the other marker's literal AND its reason, so the report groups
    under a key like ``dual-read alias  legacy-name-floor: the command``. That is
    not merely ugly — the reason is the grouping key, so two lines making the
    same claim stop collapsing together, which is the one thing the grouping is
    for.

    ``.lower()`` on both sides of the comparison: the pattern is
    case-insensitive, so a marker typed ``Legacy-Name-OK`` matches while ``kind``
    is always normalised. Comparing raw finds nothing and quietly degrades every
    oddly-cased line to "(no reason given)".

    Empty string when the marker is not found, which cannot happen for a line
    that :func:`_kind` classified — the caller turns it into "(no reason given)"
    either way.
    """
    matches = list(EXEMPT_RE.finditer(text))
    here = next(
        (i for i, m in enumerate(matches) if m.group("marker").lower() == kind), None
    )
    if here is None:
        return ""
    start = matches[here].end()
    stop = matches[here + 1].start() if here + 1 < len(matches) else len(text)
    return text[start:stop].lstrip(": ").strip()


# Above this many lines sharing one reason, the list is collapsed to a count.
# Four is where a homogeneous block stops being read line by line; below it the
# individual lines are still the more useful form.
_EXEMPTION_GROUP_AT = 4


def _git(args: list[str]) -> str:
    """git, with ``grep``'s no-match exit treated as an empty result.

    ``git grep`` exits 1 when nothing matched, which is the ordinary outcome for a
    clean tree rather than an error; a bad tree-ish exits 128 and is raised, so a
    mistyped base cannot read as "no matches" and quietly pass the gate.

    What exit 1 does NOT distinguish is a pathspec that matches nothing — git
    reports that the same way, with an empty stderr. That is why
    :func:`main` refuses to pass when BOTH trees come back empty.
    """
    # check=False deliberately: the return code is the signal here, not an error.
    #
    # The encoding is pinned rather than left to the locale. ``text=True`` alone
    # decodes with ``locale.getpreferredencoding()``, which is UTF-8 on the CI
    # runner but a legacy codepage on a Windows workstation — cp1255, cp1251,
    # cp1252, whatever the machine is set to. The tree has non-ASCII bytes in it
    # (em dashes in prose, accented names in fixtures), so on those machines the
    # decode raises UnicodeDecodeError inside subprocess's reader thread and the
    # script dies before it prints anything. It is not a gate failure — the gate
    # simply cannot be run locally, which is where you want to run it first.
    # ``errors="replace"`` keeps an undecodable byte from being fatal: this
    # counts occurrences of an ASCII name, so a mangled character elsewhere on
    # the line changes nothing about the match.
    proc = subprocess.run(
        args,
        capture_output=True,
        text=True,
        check=False,
        encoding="utf-8",
        errors="replace",
    )
    if proc.returncode == 0:
        return proc.stdout
    if proc.returncode == 1:
        return ""
    raise RuntimeError(
        f"{' '.join(args)} failed ({proc.returncode}): {proc.stderr.strip()}"
    )


def _grep(
    tree: str | None, pathspec: str | list[str] = ":/"
) -> list[tuple[str, str, str, str | None]]:
    """``(path, lineno, text, kind)`` for every matching line.

    ``kind`` is the marker literal exempting the line, or ``None`` for a line
    that carries none — see :func:`_kind`. A kind rather than a bool because the
    report has to separate the two claims a marker can make.

    Exempt lines are returned rather than dropped so the caller can report what a
    change newly exempted — see :func:`main`.

    ``tree=None`` reads the working tree. ``-I`` skips binary files. ``--full-name``
    makes paths repo-relative whatever the working directory, which the ``:/``
    pathspec then matches against the whole repo rather than a subtree.

    ``-z`` is what makes the parse safe rather than merely usually-right. Without
    it the record is colon-separated and a colon in either the path (legal on
    Linux, which is what CI runs on) or the matched text shifts every field after
    it: the line is attributed to a path that does not exist, the real file's
    count never rises, and the gate passes while appearing to work. With ``-z``
    the fields are NUL-separated and only the ``<tree>:`` prefix is colon-joined —
    and that one is a string this function passed in, so it can be stripped by
    length instead of by searching.
    """
    args = ["git", "grep", "-I", "-i", "-n", "-z", "--full-name", "-e", LEGACY_NAME]
    if tree is not None:
        args.append(tree)
    args.append("--")
    args += [pathspec] if isinstance(pathspec, str) else pathspec

    prefix = f"{tree}:" if tree is not None else ""

    out: list[tuple[str, str, str, str | None]] = []
    # Records are newline-terminated (a matched line cannot contain one) and
    # their three fields are NUL-separated.
    for record in _git(args).split("\n"):
        if not record:
            continue
        parts = record.split("\0", 2)
        if len(parts) != 3:
            continue
        path, lineno, text = parts
        if prefix:
            if not path.startswith(prefix):
                continue
            path = path[len(prefix) :]
        out.append((path, lineno, text, _kind(text)))
    return out


def _changed_paths(base: str) -> set[str] | None:
    """Every path this change touched, per git. ``None`` if the diff failed.

    What selects the files the exemption report talks about. The exempt tally
    cannot do it: a change that removes one exemption and adds another in the
    same file is net zero, so a rise-based filter never looks at that file and
    the new exemption is never printed — the one thing the report exists to stop
    happening quietly. Asking git which files moved has no such blind spot.

    ``None`` rather than an empty set on failure, because the two mean opposite
    things to the caller: "could not tell" must fall back to the old tally-based
    selection, while "nothing changed" must select nothing.

    ``-z`` for the same reason :func:`_grep` passes it, and it is load bearing
    here in a way that is easy to miss. Without it git honours ``core.quotePath``
    and returns a path holding any non-ASCII byte C-quoted — ``café.py`` comes
    back as the ten characters ``"caf\\303\\251.py"``, quotes included. Every
    other path in this module is raw, because ``_grep`` reads them with ``-z``,
    so a quoted path matches nothing in ``after`` and the file drops silently out
    of the selection below. It then falls back to the risen tally alone, which
    reopens the net-zero-swap hole this function exists to close — for exactly
    the files the tree is known to contain, since ``_git`` pins UTF-8 precisely
    because there are accented names in the fixtures.
    """
    try:
        return {
            path
            for path in _git(["git", "diff", "--name-only", "-z", base]).split("\0")
            if path
        }
    except RuntimeError:
        return None


def _added_lines(base: str, path: str) -> set[int] | None:
    """Line numbers this change actually added to ``path``, per git's own diff.

    Used for the failure report only, never for the decision. The decision
    compares text because a per-line diff calls every move an addition — but the
    report has the opposite problem, and needs exactly what the diff knows.

    Without it the report spends a text-keyed budget in file order, which assumes
    the first occurrence of a text is the new one. Line order says nothing about
    that. A file holding an untouched line and a new line with identical text
    gets the untouched one named, and the real addition is never printed — the
    reader is sent to a line that has not changed, for a gate whose whole output
    is "here is the line you added".

    ``None`` on failure, and the caller falls back to naming every occurrence of
    the minted text: too many lines is a nuisance, none is a dead end.

    ``None`` rather than an empty set, because once the exemption report selects
    files by what git says changed rather than by a risen tally, an empty result
    is a real and common answer — a file this change only DELETED from adds no
    lines, and every exempt line it still holds predates the change. Collapsing
    that into the failure case would reprint the whole pile for exactly the files
    that deserve none of it, which is the bug #894 fixed, reintroduced through
    the back door.
    """
    try:
        out = _git(["git", "diff", "-U0", base, "--", _literal(path)])
    except RuntimeError:
        return None

    added: set[int] = set()
    lineno = 0
    for line in out.splitlines():
        if line.startswith("@@"):
            # ``@@ -a,b +c,d @@`` — c is where the added run starts.
            match = re.search(r"\+(\d+)", line)
            lineno = int(match.group(1)) if match else 0
        elif line.startswith("+") and not line.startswith("+++"):
            added.add(lineno)
            lineno += 1
    return added


def _literal(path: str) -> str:
    """A pathspec that means exactly this path.

    The same hazard one level up: a bare path is interpreted as a pathspec, so one
    containing ``*``, ``?`` or a leading ``:`` would match the wrong files or be
    read as pathspec magic. ``:(literal)`` disables both.
    """
    return f":(literal){path}"


def _release_please_branch() -> bool:
    """True when CI builds release-please's own PR branch.

    release-please regenerates per-package CHANGELOGs by quoting merged PR
    titles verbatim, so titles that legitimately carried the old brand
    (history — rule 2 says never edit it) resurface as lines this tally
    cannot tell from fresh minting. Only that bot's branches get the
    exemption; a human editing a CHANGELOG still answers to the gate.
    GITHUB_HEAD_REF is set by Actions on pull_request runs and absent
    locally, so local runs keep full coverage.
    """
    return os.environ.get("GITHUB_HEAD_REF", "").startswith("release-please--")


class Scan(NamedTuple):
    """One pass over a tree, and everything the gate needs from it.

    ``by_file`` maps path to the text of its non-exempt matching lines and how
    many times each appears; ``total`` is the same tally repo-wide.
    ``exempt_by_file`` is the same shape for marked lines, which are reported
    but never gated on.

    Marked lines are held per file, not as a bare repo-wide tally, because the
    removal report has to name the file a vanished line came from — the same
    context :func:`_report_excused_moves` prints, and for the same reason: a
    reviewer who cannot locate the line cannot check whether the alias survived
    the rewording. Both views are needed and both derive from this one field.

    Text is whitespace-stripped. A line that moves into a class body or a deeper
    block gets re-indented on the way, and an indentation-sensitive comparison
    would call that new text. What is being compared is whether the repo already
    had this name written this way, which indentation does not change.

    One scan rather than three: the counts the ratchet holds flat are just
    ``sum(by_file[path].values())``, so deriving them here keeps a single
    definition of "a line that counts" instead of the same rule written out in
    three places that have to agree.
    """

    by_file: dict[str, Counter[str]]
    total: Counter[str]
    exempt_by_file: dict[str, Counter[str]]

    def counts(self) -> Counter[str]:
        """Non-exempt lines per file — what the ratchet holds flat."""
        return Counter({path: sum(c.values()) for path, c in self.by_file.items()})

    def exempt(self) -> Counter[str]:
        """Marked lines per file — what the new-exemption report examines."""
        return Counter(
            {path: sum(c.values()) for path, c in self.exempt_by_file.items()}
        )


def scan(tree: str | None, pathspec: str | list[str] = ":/") -> Scan:
    """Read a tree once. ``tree=None`` is the working tree."""
    by_file: dict[str, Counter[str]] = {}
    total: Counter[str] = Counter()
    # Not split by kind, and it does not want to be: the per-file view only
    # SELECTS files for the report, which re-greps them and reads each line's
    # kind first-hand, and the keys are text that still contains its own marker,
    # so the kind is recoverable from the key. Splitting would be a second
    # definition of the same fact.
    exempt_by_file: dict[str, Counter[str]] = {}
    for path, _, text, kind in _grep(tree, pathspec):
        stripped = text.strip()
        if kind is not None:
            exempt_by_file.setdefault(path, Counter())[stripped] += 1
            continue
        by_file.setdefault(path, Counter())[stripped] += 1
        total[stripped] += 1
    return Scan(by_file, total, exempt_by_file)


def _updated_scan(before: Scan, tree: str, paths: list[str]) -> Scan:
    """Apply one commit by rescanning only its changed paths."""
    if not paths:
        return before

    by_file = before.by_file.copy()
    exempt_by_file = before.exempt_by_file.copy()
    total = before.total.copy()
    for path in paths:
        total.subtract(by_file.pop(path, Counter()))
        exempt_by_file.pop(path, None)

    changed = scan(tree, [_literal(path) for path in paths])
    by_file.update(changed.by_file)
    exempt_by_file.update(changed.exempt_by_file)
    total.update(changed.total)
    return Scan(by_file, +total, exempt_by_file)


def _transition_paths(before: str, after: str | None = None) -> list[str]:
    """Tracked paths changed between two trees, or from before to worktree."""
    args = ["git", "diff", "--name-only", "-z", "--no-renames", before]
    if after is not None:
        args.append(after)
    args.append("--")
    return [path for path in _git(args).split("\0") if path]


class _ChangeSummary(NamedTuple):
    """Gross causes behind the non-exempt count's net movement."""

    added: int
    annotated: int
    removed: int
    moved: int
    net: int


# Ordinary gate runs must stay bounded. A caller asking for --report is
# explicitly asking for the archaeology and remains uncapped.
_GATE_REPLAY_LIMIT = 64


def _only_inserts(before: str, after: str) -> bool:
    """Whether deleting one contiguous insertion from ``after`` yields ``before``."""
    inserted = len(after) - len(before)
    if inserted <= 0:
        return False
    mismatch = next(
        (
            i
            for i, (old, new) in enumerate(zip(before, after, strict=False))
            if old != new
        ),
        len(before),
    )
    return after[mismatch + inserted :] == before[mismatch:]


def _transition_summary(base: Scan, head: Scan) -> _ChangeSummary:
    """Classify one tree-to-tree transition without affecting the gate."""
    lost = {
        (path, text): n
        for path, lines in base.by_file.items()
        for text, n in (lines - head.by_file.get(path, Counter())).items()
    }
    gained = {
        (path, text): n
        for path, lines in head.by_file.items()
        for text, n in (lines - base.by_file.get(path, Counter())).items()
    }
    gained_exempt = {
        (path, text): n
        for path, lines in head.exempt_by_file.items()
        for text, n in (lines - base.exempt_by_file.get(path, Counter())).items()
    }

    annotated = 0
    for (destination, marked), available in sorted(gained_exempt.items()):
        candidates = sorted(
            (key for key, n in lost.items() if n and _only_inserts(key[1], marked)),
            key=lambda key: (key[0] != destination, len(marked) - len(key[1]), key),
        )
        for key in candidates:
            matched = min(available, lost[key])
            annotated += matched
            available -= matched
            lost[key] -= matched
            if not available:
                break

    moved = 0
    for (destination, text), available in sorted(gained.items()):
        sources = sorted(
            key
            for key, n in lost.items()
            if n and key[0] != destination and key[1] == text
        )
        for key in sources:
            matched = min(available, lost[key])
            moved += matched
            available -= matched
            lost[key] -= matched
            gained[(destination, text)] -= matched
            if not available:
                break

    return _ChangeSummary(
        added=sum(gained.values()),
        annotated=annotated,
        removed=sum(lost.values()),
        moved=moved,
        net=sum(head.counts().values()) - sum(base.counts().values()),
    )


